"""Frozen multi-guide IRIS experiment on the actual seven-joint robot scene."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import time
import numpy as np
from pydrake.geometry.optimization import HPolyhedron
from .build_scene import build_scene
from .green_room_gcs import guide_edge_validator, region_holdout
from .green_room_iris import grow_cover
from .compare_frozen_operation_graph import compare


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',required=True);p.add_argument('--output',required=True)
    args=p.parse_args();source=Path(args.source);out=Path(args.output);out.mkdir(parents=True,exist_ok=False)
    config=json.loads((source/'scene_config_snapshot.json').read_text())
    original=json.loads((source/'reach_cover.json').read_text())
    report=json.loads((source/'result.json').read_text())
    records=original['regions'];base=np.array(report['dock_q'])
    reference=np.array([records[0]['guide_start']]+[r['guide_end'] for r in records])
    # Prespecified two-sided perturbations. They are guides, never executed
    # directly; all resulting regions are generated by official IRIS-NP2.
    protocol={'branches':[{'joint':j,'amplitude':a} for j in (0,6) for a in (-.06,.06)],
              'queries':[[0,1],[0,.85],[.15,1],[.15,.85],[.25,.75]],
              'source':str(source),'scope':'Same-scene guided local multi-route cover; not global route discovery, independent scenes, or RRT comparison',
              'source_hashes':{f.name:hashlib.sha256(f.read_bytes()).hexdigest() for f in [source/'reach_cover.json',source/'scene_config_snapshot.json']}}
    (out/'protocol.json').write_text(json.dumps(protocol,indent=2))
    scene=build_scene(config=config,visualize=False)
    validator=guide_edge_validator(scene,base,reference[0],scene.gripper_open_positions,semantic=True)
    merged=copy.deepcopy(records);branches=[];began=time.perf_counter()
    for bid,spec in enumerate(protocol['branches']):
        path=reference.copy();path[:,spec['joint']]+=spec['amplitude']*np.sin(np.linspace(0,np.pi,len(path)))
        row=dict(spec,id=bid);tick=time.perf_counter()
        try:
            if not all(validator(a,b) for a,b in zip(path,path[1:])):
                raise RuntimeError('Guide fails independent geometry/room edge check')
            _,new,_=grow_cover(scene,base,path,scene.gripper_open_positions,semantic=True)
            audit=region_holdout(scene,base,new,scene.gripper_open_positions)
            row['holdout']=audit
            if any(audit[k] for k in ('collisions','raw_grasp_violations','semantic_violations')):
                raise RuntimeError('Independent region holdout rejected branch')
            row.update(accepted=True,region_count=len(new));merged.extend(new)
        except Exception as e:
            row.update(accepted=False,error=str(e))
        row['seconds']=time.perf_counter()-tick;branches.append(row)
        (out/'branches.json').write_text(json.dumps(branches,indent=2));print('BRANCH',row,flush=True)
    regions=[HPolyhedron(np.array(r['A']),np.array(r['b'])) for r in merged]
    # Cheap necessary box intersection rejection, then exact convex feasibility.
    lo=np.array([r['lower'] for r in merged]);hi=np.array([r['upper'] for r in merged]);edges=[]
    for i in range(len(regions)):
        possible=np.flatnonzero(np.all(lo<=hi[i]+1e-9,axis=1)&np.all(hi>=lo[i]-1e-9,axis=1))
        for j in possible:
            if j>i and regions[i].IntersectsWith(regions[j]):edges.extend([(i,int(j)),(int(j),i)])
    cover_seconds=time.perf_counter()-began
    results=[]
    for qid,(a,b) in enumerate(protocol['queries']):
        start=reference[round(a*(len(reference)-1))];goal=reference[round(b*(len(reference)-1))]
        query=out/f'query_{qid:02d}';query.mkdir()
        query_records=copy.deepcopy(merged);query_records[0]['guide_start']=start.tolist();query_records[-1]['guide_end']=goal.tolist()
        data={'region_method':'iris_np2','regions':query_records,'edges':edges,
              'sources':[i for i,r in enumerate(regions) if r.PointInSet(start,1e-7)],
              'targets':[i for i,r in enumerate(regions) if r.PointInSet(goal,1e-7)]}
        (query/'reach_cover.json').write_text(json.dumps(data));(query/'scene_config_snapshot.json').write_text(json.dumps(config))
        row=compare(query,'reach');row['query_id']=qid;results.append(row)
        (out/'comparison.json').write_text(json.dumps(results,indent=2))
        print('QUERY',qid,[(r['method'],r.get('objective'),r.get('solve_seconds')) for r in row['results']],flush=True)
    (out/'summary.json').write_text(json.dumps({'regions':len(regions),'undirected_edges':len(edges)//2,
        'cover_seconds':cover_seconds,'accepted_branches':sum(b['accepted'] for b in branches),
        'scope':protocol['scope']},indent=2))

if __name__=='__main__':main()
